/* The email box of the edit form. A paper placeholder is shown as an empty
   box with PAPER_EMAIL_DISPLAY as its placeholder text, so neither the
   generated address nor the display text can be edited by accident. */
const editableEmail = (storedEmail: string) =>
  isPaperPlaceholderEmail(storedEmail) ? "" : storedEmail;

/* What the edit form saves: a blank box on a paper entry keeps the stored
   placeholder (the rider still has no email); anything typed replaces it. */
const emailToSave = (draftEmail: unknown, storedEmail: string) => {
  const typed = String(draftEmail ?? "").trim();
  return typed === "" && isPaperPlaceholderEmail(storedEmail) ? storedEmail : typed;
};

/* Addresses on the placeholder domain are generated by the database only. */
const reservedEmailError = (draftEmail: unknown, storedEmail: string, ownerLabel?: string) => {
  const typed = String(draftEmail ?? "").trim();

  if (typed === "" || typed.toLowerCase() === storedEmail.trim().toLowerCase()) {
    return null;
  }

  return isPaperPlaceholderEmail(typed)
    ? `${ownerLabel ? `${ownerLabel}: ` : ""}Addresses on ${PAPER_EMAIL_DOMAIN} are reserved for paper entries. Leave the box blank if the rider has no email.`
    : null;
};

